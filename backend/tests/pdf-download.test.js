import test, { after, before } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PDFParse } from 'pdf-parse';

import { generatePdf } from '../services/pdfGeneration.js';
import { createSecureDownloadToken, ensureGeneratedDirectory } from '../services/generatedFiles.js';
import { app } from '../server.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
let server;
let baseUrl;

before(async () => {
  server = app.listen(0, '127.0.0.1');
  await new Promise((resolve, reject) => {
    server.once('listening', resolve);
    server.once('error', reject);
  });
  baseUrl = `http://127.0.0.1:${server.address().port}`;
});

after(async () => {
  if (server?.listening) {
    await new Promise((resolve, reject) => {
      server.close((error) => error ? reject(error) : resolve());
    });
  }
});

test('real PDF generation produces a valid multi-page document and secure token', async () => {
  await ensureGeneratedDirectory();

  const filename = 'audit-sample-multipage.pdf';
  const filePath = path.join(__dirname, '../generated', filename);
  const content = [
    'Executive Summary',
    'Revenue improved after launch, with stronger retention and faster customer onboarding.',
    'The team should continue to prioritize reliability, observability, and fast iteration cycles.',
    'Key actions:',
    '- Improve PDF delivery safety and secure access controls.',
    '- Add caching and service-level timeouts for expensive requests.',
    '- Keep the model config environment-based and validate it in CI.',
    '',
    'Appendix',
    'This PDF was generated by the backend to validate the real document path.',
  ].join('\n\n');

  const pdfBuffer = await generatePdf({
    title: 'Quarterly Strategy Review',
    content,
  });

  await fs.writeFile(filePath, pdfBuffer);

  const token = createSecureDownloadToken({
    filename,
    filePath,
    userId: 'audit-user',
  });

  const parser = new PDFParse({ data: pdfBuffer });
  let parsed;
  try {
    parsed = await parser.getText();
  } finally {
    await parser.destroy();
  }

  assert.equal(pdfBuffer.subarray(0, 5).toString('latin1'), '%PDF-');
  assert.ok(parsed.total >= 1);
  assert.ok(parsed.text.length > 50);

  const validRes = await fetch(`${baseUrl}/generated/${token}/${encodeURIComponent(filename)}`);
  assert.equal(validRes.status, 200);
  assert.match(validRes.headers.get('content-type') || '', /application\/pdf/i);

  const invalidRes = await fetch(`${baseUrl}/generated/invalid-token/${encodeURIComponent(filename)}`);
  assert.equal(invalidRes.status, 403);

  const publicRes = await fetch(`${baseUrl}/generated/${encodeURIComponent(filename)}`);
  assert.equal(publicRes.status, 404);
  const publicBody = await publicRes.json();
  assert.equal(publicBody.message, 'Route not found.');
  assert.equal(publicBody.path, `/generated/${encodeURIComponent(filename)}`);
});
