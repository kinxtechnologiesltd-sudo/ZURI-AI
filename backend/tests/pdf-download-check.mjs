import fs from 'node:fs/promises';
import path from 'node:path';
import pdfParse from 'pdf-parse';
import { generatePdf } from '../services/pdfGeneration.js';
import { createSecureDownloadToken, ensureGeneratedDirectory } from '../services/generatedFiles.js';

await import('../server.js');

const generatedDir = path.join(process.cwd(), 'backend', 'generated');
await ensureGeneratedDirectory();

const filename = 'audit-sample-multipage.pdf';
const filePath = path.join(generatedDir, filename);
const title = 'Quarterly Strategy Review';
const content = [
  'Executive Summary',
  'Revenue improved after launch, with stronger retention and faster customer onboarding.',
  'The team should continue to prioritize reliability, observability, and fast iteration cycles.',
  'Key actions:',
  '- Improve PDF delivery safety and secure access controls.',
  '- Add caching and service-level timeouts for expensive requests.',
  '- Keep the model config environment-based and validate it in CI.',
  '',
  'Appendix',
  'This PDF was generated by the backend to validate the real document path.',
].join('\n\n');

const pdfBuffer = await generatePdf({ title, content });
await fs.writeFile(filePath, pdfBuffer);
const token = createSecureDownloadToken({ filename, filePath, userId: 'audit-user' });
const parsed = await pdfParse(pdfBuffer);

console.log('PDF_SIZE_BYTES=' + pdfBuffer.length);
console.log('PDF_HEADER=' + pdfBuffer.toString('latin1', 0, 5));
console.log('PDF_PAGE_COUNT=' + parsed.numpages);
console.log('PDF_TEXT_CHARS=' + parsed.text.length);
console.log('PDF_TEXT_PREVIEW=' + parsed.text.slice(0, 120).replace(/\s+/g, ' '));

const validRes = await fetch(`http://localhost:3001/generated/${token}/${encodeURIComponent(filename)}`);
console.log('VALID_STATUS=' + validRes.status);
console.log('VALID_CONTENT_TYPE=' + validRes.headers.get('content-type'));
console.log('VALID_PREVIEW=' + (await validRes.text()).slice(0, 20));

const invalidRes = await fetch(`http://localhost:3001/generated/invalid-token/${encodeURIComponent(filename)}`);
console.log('INVALID_STATUS=' + invalidRes.status);
console.log('INVALID_BODY=' + JSON.stringify(await invalidRes.json()));

const publicRes = await fetch(`http://localhost:3001/generated/${encodeURIComponent(filename)}`);
console.log('PUBLIC_STATUS=' + publicRes.status);
console.log('PUBLIC_BODY=' + JSON.stringify(await publicRes.json()));

process.exit(0);
